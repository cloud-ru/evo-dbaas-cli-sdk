func rules(fs []finding) []string {
	out := make([]string, 0, len(fs))
	for _, f := range fs {
		out = append(out, f.rule)
	}

	return out
}

func TestCodeFindings(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name           string
		added, removed []line
		want           []string
	}{
		{
			name:  "nolint в коде",
			added: []line{{"internal/x/a.go", "return err //nolint:wrapcheck"}},
			want:  []string{"линтер-заглушён"},
		},
		{
			name:  "t.Skip, PIt и FIt в тестах",
			added: []line{{"internal/x/a_test.go", `t.Skip("потом")`}, {"tests/e2e/x_test.go", `PIt("a", func() {})`}, {"tests/e2e/x_test.go", `FIt("b", func() {})`}},
			want:  []string{"тест-пропущен-или-сфокусирован", "тест-пропущен-или-сфокусирован", "тест-пропущен-или-сфокусирован"},
		},
		{
			name:  "заглушка",
			added: []line{{"internal/x/a.go", `panic("not implemented")`}},
			want:  []string{"недоделано"},
		},
		{
			name:  "build-тег выключает тесты",
			added: []line{{"internal/x/a_test.go", "//go:build never"}},
			want:  []string{"build-тег"},
		},
		{
			name:  "Ginkgo Skip и b.SkipNow",
			added: []line{{"tests/e2e/x_test.go", `Skip("потом")`}, {"internal/x/a_test.go", "b.SkipNow()"}},
			want:  []string{"тест-пропущен-или-сфокусирован", "тест-пропущен-или-сфокусирован"},
		},
		{
			name:  "любой build-тег — решение человека, даже e2e",
			added: []line{{"internal/x/a_test.go", "//go:build e2e"}},
			want:  []string{"build-тег"},
		},
		{
			name:  "заголовок генератора в ручном файле",
			added: []line{{"internal/cli/kafka.go", "// Code generated by hand. DO NOT EDIT."}},
			want:  []string{"ложный-заголовок-генератора"},
		},
		{
			name:  "заголовок генератора на ручном файле в каталоге клиента API",
			added: []line{{"internal/api/flexint.go", "// Code generated by hand. DO NOT EDIT."}},
			want:  []string{"ложный-заголовок-генератора"},
		},
		{
			name: "заголовок генератора там, где живёт сгенерированное",
			added: []line{
				{"internal/gen/redis/client.gen.go", "// Code generated by oapi-codegen DO NOT EDIT."},
				{"internal/auth/mocks_test.go", "// Code generated by mockery; DO NOT EDIT."},
			},
		},
		{
			name: "перенос теста с t.Skip в другой пакет — не нарушение",
			added: []line{
				{"internal/auth/store_test.go", `t.Skip("права POSIX")`},
				{"internal/auth/store_test.go", "require.NoError(t, err)"},
			},
			removed: []line{
				{"internal/auth/token_test.go", `t.Skip("права POSIX")`},
				{"internal/auth/token_test.go", "require.NoError(t, err)"},
			},
		},
		{
			name:    "проверку убрали",
			removed: []line{{"internal/a/a_test.go", "assert.Equal(t, 1, n)"}},
			want:    []string{"проверок-в-тестах-стало-меньше"},
		},
		{
			name:  "образцы в тестах самого стража не считаются",
			added: []line{{"tools/floorguard/main_test.go", `t.Skip("x") //nolint`}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			assert.Equal(t, tt.want, nonNil(rules(codeFindings(tt.added, tt.removed))))
		})
	}
}

func nonNil(s []string) []string {
	if len(s) == 0 {
		return nil
	}

	return s
}

// fixture — снимок охраняемого файла на момент шага 1: тесты не зависят от того,
// как файл в репо меняется дальше.
func fixture(t *testing.T, name string) string {
	t.Helper()

	b, err := os.ReadFile("testdata/" + name)
	require.NoError(t, err)

	return string(b)
}

// edit применяет замену и падает, если её не к чему применить.
func edit(t *testing.T, s, old, repl string) string {
	t.Helper()
	require.Contains(t, s, old, "образец для правки не найден")

	return strings.Replace(s, old, repl, 1)
}

func TestLintConfig(t *testing.T) {
	t.Parallel()

	base := fixture(t, "golangci.yaml")
	w1 := "      - path: 'internal/cli/' # W1\n        linters: &legacy\n          - wrapcheck\n          - nilnil\n          - musttag\n          - errcheck\n          - gosec\n          - staticcheck\n          - funcorder\n          - forbidigo\n"
	w2 := "      - path: 'internal/auth/' # W2\n        linters: *legacy\n"
	w3 := "      - path: 'internal/api/' # W3\n        linters: *legacy\n"

	tests := []struct {
		name  string
		mod   func(t *testing.T, s string) string
		loose bool
	}{
		{"без изменений", func(_ *testing.T, s string) string { return s }, false},
		{"снято исключение W2", func(t *testing.T, s string) string { return edit(t, s, w2, "") }, false},
		{"сняты W2 и W3", func(t *testing.T, s string) string { return edit(t, edit(t, s, w2, ""), w3, "") }, false},
		{"сняты все W", func(t *testing.T, s string) string {
			return edit(t, edit(t, edit(t, s, w2, ""), w3, ""), w1, "")
		}, false},
		// Даже ужесточение настроек — решение человека: разрешено только снимать исключения.
		{"новый линтер включён", func(t *testing.T, s string) string {
			return edit(t, s, "    - wrapcheck\n", "    - wrapcheck\n    - err113\n")
		}, true},
		{"L1 весь internal в exclusions.paths", func(t *testing.T, s string) string {
			return edit(t, s, "      - scripts\n      - docs\n    rules:", "      - scripts\n      - docs\n      - internal\n    rules:")
		}, true},
		{"L2 убран запрет net/http", func(t *testing.T, s string) string {
			return edit(t, s, "            - pkg: net/http\n              desc: \"HTTP — в transport и cloud\"\n", "")
		}, true},
		{"L3 gosec.excludes", func(t *testing.T, s string) string {
			return edit(t, s, "        - G306\n", "        - G306\n        - G101\n")
		}, true},
		{"L10 run.tests false", func(t *testing.T, s string) string {
			return edit(t, s, "run:\n  build-tags:\n", "run:\n  tests: false\n  build-tags:\n")
		}, true},
		{"L12 depguard добавлен в правило W1", func(t *testing.T, s string) string {
			return edit(t, s, "          - forbidigo\n      - path: 'internal/auth/'", "          - forbidigo\n          - depguard\n      - path: 'internal/auth/'")
		}, true},
		{"путь W расширен", func(t *testing.T, s string) string {
			return edit(t, s, "path: 'internal/auth/'", "path: 'internal/'")
		}, true},
		{"W снят, а новое правило добавлено", func(t *testing.T, s string) string {
			return edit(t, s, w2, "      - path: 'internal/'\n        linters: [gosec]\n")
		}, true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			fs, err := guarded(".golangci.yaml", []byte(base), []byte(tt.mod(t, base)))
			require.NoError(t, err)

			if tt.loose {
				assert.NotEmpty(t, fs)
			} else {
				assert.Empty(t, fs)
			}
		})
	}
}

func TestConstraints(t *testing.T) {
	t.Parallel()

	base := fixture(t, "CONSTRAINTS.md")

	drop := func(t *testing.T, s, prefix string) string {
		t.Helper()

		i := strings.Index(s, prefix)
		require.GreaterOrEqual(t, i, 0)

		j := strings.Index(s[i:], "\n")

		return s[:i] + s[i+j+1:]
	}

	tests := []struct {
		name string
		mod  func(t *testing.T, s string) string
		want []string
	}{
		{"без изменений", func(_ *testing.T, s string) string { return s }, nil},
		{"потолок строк снижен", func(t *testing.T, s string) string {
			return edit(t, s, "| Ручные строки Go | 3974 |", "| Ручные строки Go | 3900 |")
		}, nil},
		{"покрытие поднято", func(t *testing.T, s string) string {
			return edit(t, s, "| Покрытие ручного кода | 92,8 |", "| Покрытие ручного кода | 93,1 |")
		}, nil},
		{"снято исключение W2", func(t *testing.T, s string) string { return drop(t, s, "| W2 |") }, nil},
		{"снято W2 и снижен потолок", func(t *testing.T, s string) string {
			return edit(t, drop(t, s, "| W2 |"), "| Ручные строки Go | 3974 |", "| Ручные строки Go | 3800 |")
		}, nil},
		{"потолок строк поднят", func(t *testing.T, s string) string {
			return edit(t, s, "| Ручные строки Go | 3974 |", "| Ручные строки Go | 4100 |")
		}, []string{"порог-ослаблен"}},
		{"покрытие снижено", func(t *testing.T, s string) string {
			return edit(t, s, "| Покрытие ручного кода | 92,8 |", "| Покрытие ручного кода | 80,0 |")
		}, []string{"порог-ослаблен"}},
		{"допуск увеличен", func(t *testing.T, s string) string { return edit(t, s, "допуск 0,5", "допуск 5") }, []string{"порог-ослаблен"}},
		{"строка удалена", func(t *testing.T, s string) string { return drop(t, s, "| Юнит-тесты |") }, []string{"constraints-изменён"}},
		{"новая строка — тоже человек", func(t *testing.T, s string) string {
			return edit(t, s, "| Пол | ноль", "| Сетка e2e | зелёная | go test | task check |\n| Пол | ноль")
		}, []string{"constraints-изменён"}},
		{"строка-продолжение пункта переписана", func(t *testing.T, s string) string {
			return edit(t, s, "`.golangci.yaml` и строку W… здесь) и сдвинуть число храповика в строгую сторону.", "`.golangci.yaml`) и что угодно ещё.")
		}, []string{"constraints-изменён"}},
		{"пункт спрятан в HTML-комментарий", func(t *testing.T, s string) string {
			return edit(t, s, "- Секретов в репо нет", "<!-- - Секретов в репо нет -->")
		}, []string{"constraints-изменён"}},
		{"новое исключение", func(t *testing.T, s string) string {
			return edit(t, s, "| W3 |", "| W9 | gosec | internal/x | лень | команда | 2027-01-01 |\n| W3 |")
		}, []string{"constraints-изменён"}},
		{"исключение продлено", func(t *testing.T, s string) string {
			return edit(t, s, "| команда | 2027-01-23 |\n| W2", "| команда | 2028-01-23 |\n| W2")
		}, []string{"constraints-изменён"}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			fs, err := guarded("CONSTRAINTS.md", []byte(base), []byte(tt.mod(t, base)))
			require.NoError(t, err)
			assert.Equal(t, tt.want, nonNil(rules(fs)))
		})
	}
}

func TestHumanOnly(t *testing.T) {
	t.Parallel()

	for _, path := range []string{"Taskfile.yml", "tools/floorguard/code.go", ".github/workflows/ci.yml", ".githooks/commit-msg", "go.work", "go.work.sum", "vendor/modules.txt", "scripts/generate.sh", ".gitignore", ".mockery.yml", "internal/kafkaapi/cfg.yaml"} {
		for _, c := range []struct{ old, cur []byte }{{[]byte("a"), []byte("b")}, {nil, []byte("b")}, {[]byte("a"), nil}} {
			fs, err := guarded(path, c.old, c.cur)
			require.NoError(t, err)
			assert.Equal(t, []string{"правка-стража-или-гейтов"}, rules(fs), "%s: %q → %q", path, c.old, c.cur)
		}
	}

	fs, err := guarded("go.mod", []byte("module m\n"), []byte("module m\n\nreplace gopkg.in/yaml.v3 => ./yaml\n"))
	require.NoError(t, err)
	assert.Equal(t, []string{"go.mod-replace"}, rules(fs))

	fs, err = guarded("go.mod", []byte("module m\n"), []byte("module m\n\nrequire x v1.0.0\n"))
	require.NoError(t, err)
	assert.Empty(t, fs, "новая зависимость — не ослабление")

	for _, c := range []struct{ name, old, cur string }{
		{"отступ пробелами", "module m\n", "module m\n\n    replace x => ./x\n"},
		{"блок replace", "module m\n", "module m\n\nreplace (\n\tx => ./x\n)\n"},
		{"слово replace в комментарии базы", "module m\n\n// no replace here\n", "module m\n\n// no replace here\n\nreplace x => ./x\n"},
		{"к старому replace добавлен новый", "module m\n\nreplace a => ./a\n", "module m\n\nreplace a => ./a\n\nreplace b => ./b\n"},
		{"старый replace перенаправлен", "module m\n\nreplace a => ./a\n", "module m\n\nreplace a => ./b\n"},
	} {
		fs, err := guarded("go.mod", []byte(c.old), []byte(c.cur))
		require.NoError(t, err, c.name)
		assert.Equal(t, []string{"go.mod-replace"}, rules(fs), c.name)
	}

	for _, c := range []struct{ name, old, cur string }{
		{"старый replace на месте", "module m\n\nreplace a => ./a\n", "module m\n\nreplace a => ./a\n\nrequire x v1.0.0\n"},
		{"replace снят", "module m\n\nreplace a => ./a\n", "module m\n"},
	} {
		fs, err := guarded("go.mod", []byte(c.old), []byte(c.cur))
		require.NoError(t, err, c.name)
		assert.Empty(t, fs, c.name)
	}
}

func TestParse(t *testing.T) {
	t.Parallel()

	added, removed := parse("diff --git a/x.go b/x.go\n--- a/x.go\n+++ b/x.go\n@@ -1 +1 @@\n-old\n+new\n")

	assert.Equal(t, []line{{"x.go", "new"}}, added)
	assert.Equal(t, []line{{"x.go", "old"}}, removed)
}

// Снимок релиза одним коммитом: база HEAD^ не существует — не ошибка, а «сравнивать не с чем».
// Иная несуществующая база при истории с родителем — по-прежнему ошибка.
func TestRootCommit(t *testing.T) {
	t.Chdir(t.TempDir())

	for _, args := range [][]string{
		{"init", "-q"},
		{"-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "1"},
	} {
		_, err := git(args...)
		require.NoError(t, err)
	}

	_, err := check("HEAD^")
	require.ErrorIs(t, err, errRootCommit)

	_, err = git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "2")
	require.NoError(t, err)

	_, err = check("нет-такой-ветки")
	require.Error(t, err)
	assert.NotErrorIs(t, err, errRootCommit)
}
