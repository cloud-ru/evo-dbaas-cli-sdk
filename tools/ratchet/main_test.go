package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func write(t *testing.T, name, body string) string {
	t.Helper()

	p := filepath.Join(t.TempDir(), name)
	require.NoError(t, os.WriteFile(p, []byte(body), 0o600))

	return p
}

func TestReadRecorded(t *testing.T) {
	t.Parallel()

	p := write(t, "C.md", "| Ручные строки Go | 3974 | не растёт |\n| Пройденные тесты | 412 | не падает |\n| Покрытие ручного кода | 92,8 | не падает (допуск 0,5) |\n")

	got, err := readRecorded(p)
	require.NoError(t, err)
	assert.InDelta(t, 92.8, got["cover"], 1e-9)
	assert.InDelta(t, 0.5, got["tolerance"], 1e-9)
	assert.InDelta(t, 412, got["tests"], 0)

	_, err = readRecorded(write(t, "C.md", "| Ручные строки Go | 3974 |\n| Пройденные тесты | 1 |\n| Покрытие ручного кода | 92,8 | не падает |\n"))
	require.Error(t, err, "без допуска — ошибка, а не молчаливый ноль")

	_, err = readRecorded(write(t, "C.md", "| Покрытие ручного кода | 92,8 | допуск 0,5 |\n"))
	require.Error(t, err, "без строки тестов — ошибка")
}

func TestManualCoverage(t *testing.T) {
	t.Parallel()

	p := write(t, "c.out", "mode: set\n"+
		"m/a.go:1.1,2.2 3 1\n"+
		"m/a.go:3.1,4.2 1 0\n"+
		"m/client.gen.go:1.1,2.2 100 0\n"+
		"m/tools/x/main.go:1.1,2.2 50 0\n")

	got, err := manualCoverage(p, map[string]bool{"m/client.gen.go": true})
	require.NoError(t, err)
	assert.InDelta(t, 75.0, got, 1e-9, "сгенерированное и tools/ не считаются")

	_, err = manualCoverage(write(t, "c.out", "mode: set\n"), nil)
	require.Error(t, err)
}

